#!/usr/bin/env python3
"""Fail closed on semantic ODCS/dbt drift without treating YAML wrapping as drift.

The Data Contract CLI serializes unrelated YAML scalars while synchronizing
one model. Compare the parsed dbt declarations for non-managed YAML files,
but require an exact generated representation for the ODCS-owned model.
Files are read-only; the caller creates a disposable synchronized project.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

MANAGED_MODEL = Path("gold/dimensions/dim_election_cycle.yml")
YAML_SUFFIXES = {".yml", ".yaml"}


def _inventory(root: Path) -> dict[Path, Path]:
    if not root.is_dir() or root.is_symlink():
        raise ValueError(f"Models directory missing or symlinked: {root}")
    inventory: dict[Path, Path] = {}
    for file in root.rglob("*"):
        if file.is_symlink():
            raise ValueError(f"Symlink not permitted in model tree: {file}")
        if file.is_file():
            inventory[file.relative_to(root)] = file
    return inventory


def compare_model_trees(
    committed: Path, generated: Path, *, managed_models: set[Path] | None = None
) -> list[str]:
    """List discrepancies; YAML representation alone is not a discrepancy.

    Model lists and data_tests arrays remain order-sensitive. Types,
    descriptions, tags, meta and unrelated model declarations are checked.
    The managed model file is stricter: it must match regenerated bytes.
    """
    managed = {MANAGED_MODEL} if managed_models is None else set(managed_models)
    if not managed:
        raise ValueError("At least one managed ODCS model must be specified")
    old = _inventory(committed)
    new = _inventory(generated)
    errors: list[str] = []
    for path in sorted(old.keys() - new.keys()):
        errors.append(f"Deleted by sync: {path}")
    for path in sorted(new.keys() - old.keys()):
        errors.append(f"Unexpected generated file: {path}")
    for owned in sorted(managed):
        if owned not in old or owned not in new:
            errors.append(f"Missing ODCS-owned model: {owned}")
    for relative in sorted(old.keys() & new.keys()):
        source, candidate = old[relative], new[relative]
        a, b = source.read_bytes(), candidate.read_bytes()
        if a == b:
            continue
        if relative in managed:
            errors.append(f"ODCS-managed model has byte drift: {relative}")
        elif relative.suffix.lower() in YAML_SUFFIXES:
            try:
                original = yaml.safe_load(a)
                synchronized = yaml.safe_load(b)
            except yaml.YAMLError as exc:
                errors.append(f"Cannot parse {relative}: {exc}")
                continue
            if original != synchronized:
                errors.append(f"Semantic dbt YAML drift: {relative}")
        else:
            errors.append(f"Non-YAML byte drift: {relative}")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--committed", type=Path, required=True)
    parser.add_argument("--generated", type=Path, required=True)
    parser.add_argument("--managed", action="append", type=Path, default=None,
                        help="Managed YAML path relative to models/ (repeatable)")
    args = parser.parse_args(argv)
    try:
        discrepancies = compare_model_trees(args.committed, args.generated,
                                            managed_models=set(args.managed) if args.managed else None)
    except (OSError, ValueError) as exc:
        print(f"FAIL: cannot verify ODCS/dbt sync: {exc}", file=sys.stderr)
        return 1
    if discrepancies:
        for problem in discrepancies:
            print("FAIL: " + problem, file=sys.stderr)
        return 1
    print("PASS: ODCS-managed model byte-identical; all other dbt model declarations semantically unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
