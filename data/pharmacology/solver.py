class ClinicalModel:
    def __init__(
        self,
        con: duckdb.DuckDBPyConnection,
        pathology_id: int,
    ) -> None:
        self.con = con
        self.pathology_id = pathology_id

        self.pathology_name = (
            self._load_pathology_name()
        )

        self.presentations = (
            self._load_presentations()
        )

        self.pathology_symptoms = (
            self._load_pathology_symptoms()
        )

        self.therapeutic_effects = (
            self._load_therapeutic_effects()
        )

        self.adverse_effects = (
            self._load_adverse_effects()
        )

        self.interactions = (
            self._load_interactions()
        )

        self.symptom_names = (
            self._load_symptom_names()
        )

        self.presentation_by_id = {
            p.id: p
            for p in self.presentations
        }

        self.pathology_by_symptom = {
            s.symptom_id: s
            for s in self.pathology_symptoms
        }

        self.therapeutic_by_symptom = (
            self._index_therapeutic_by_symptom()
        )

        self.adverse_by_symptom = (
            self._index_adverse_by_symptom()
        )

        self.interaction_by_pair = {
            (
                i.presentation_a_id,
                i.presentation_b_id,
            ): i.severity
            for i in self.interactions
        }

        self.symptom_universe = frozenset(
            self.symptom_names
        )

    # ========================================================
    # LOADERS
    # ========================================================

    def _load_pathology_name(self) -> str:
        row = self.con.execute(
            """
            SELECT nome
            FROM patologia
            WHERE id = ?
            """,
            [self.pathology_id],
        ).fetchone()

        if row is None:
            raise ValueError(
                f"Patologia id={self.pathology_id} "
                "não encontrada"
            )

        return row[0]

    def _load_presentations(
        self,
    ) -> list[Presentation]:
        rows = self.con.execute(
            """
            SELECT
                a.id,
                r.nome_comercial,
                a.descricao,
                a.custo_complexidade

            FROM apresentacao AS a

            JOIN remedio AS r
              ON r.id = a.remedio_id

            ORDER BY a.id
            """
        ).fetchall()

        return [
            Presentation(
                id=row[0],
                drug_name=row[1],
                description=row[2],
                complexity_cost=float(row[3]),
            )
            for row in rows
        ]

    def _load_pathology_symptoms(
        self,
    ) -> list[PathologySymptom]:
        rows = self.con.execute(
            """
            SELECT
                ps.sintoma_id,
                s.nome,

                ps.prevalencia,
                ps.peso_clinico,

                ps.limiar_tolerancia,
                ps.limiar_controle

            FROM patologia_sintoma AS ps

            JOIN sintoma AS s
              ON s.id = ps.sintoma_id

            WHERE ps.patologia_id = ?

            ORDER BY ps.sintoma_id
            """,
            [self.pathology_id],
        ).fetchall()

        return [
            PathologySymptom(
                symptom_id=row[0],
                symptom_name=row[1],

                prevalence=float(row[2]),
                clinical_weight=float(row[3]),

                tolerance_threshold=float(row[4]),
                control_threshold=float(row[5]),
            )
            for row in rows
        ]

    def _load_therapeutic_effects(
        self,
    ) -> list[TherapeuticEffect]:
        rows = self.con.execute(
            """
            SELECT
                apresentacao_id,
                sintoma_id,
                eficacia,
                probabilidade_resposta

            FROM apresentacao_alivia
            """
        ).fetchall()

        return [
            TherapeuticEffect(
                presentation_id=row[0],
                symptom_id=row[1],
                efficacy=float(row[2]),
                response_probability=float(row[3]),
            )
            for row in rows
        ]

    def _load_adverse_effects(
        self,
    ) -> list[AdverseEffect]:
        rows = self.con.execute(
            """
            SELECT
                ae.apresentacao_id,
                ae.sintoma_id,
                s.nome,

                ae.probabilidade,
                ae.gravidade,
                ae.gravidade_peso,
                ae.peso_clinico,

                ae.risco_maximo_admissivel

            FROM apresentacao_evento_adverso AS ae

            JOIN sintoma AS s
              ON s.id = ae.sintoma_id
            """
        ).fetchall()

        return [
            AdverseEffect(
                presentation_id=row[0],
                symptom_id=row[1],
                symptom_name=row[2],

                probability=float(row[3]),
                severity=row[4],
                severity_weight=float(row[5]),
                clinical_weight=float(row[6]),

                max_admissible_risk=float(row[7]),
            )
            for row in rows
        ]

    def _load_interactions(
        self,
    ) -> list[Interaction]:
        rows = self.con.execute(
            """
            SELECT
                apresentacao_a_id,
                apresentacao_b_id,
                severidade

            FROM apresentacao_interacao
            """
        ).fetchall()

        return [
            Interaction(
                presentation_a_id=row[0],
                presentation_b_id=row[1],
                severity=float(row[2]),
            )
            for row in rows
        ]

    def _load_symptom_names(
        self,
    ) -> dict[int, str]:
        rows = self.con.execute(
            """
            SELECT id, nome
            FROM sintoma
            ORDER BY id
            """
        ).fetchall()

        return {
            row[0]: row[1]
            for row in rows
        }

    # ========================================================
    # INDEXES
    # ========================================================

    def _index_therapeutic_by_symptom(
        self,
    ) -> dict[int, list[TherapeuticEffect]]:
        result: dict[
            int,
            list[TherapeuticEffect],
        ] = {}

        for effect in self.therapeutic_effects:
            result.setdefault(
                effect.symptom_id,
                [],
            ).append(effect)

        return result

    def _index_adverse_by_symptom(
        self,
    ) -> dict[int, list[AdverseEffect]]:
        result: dict[
            int,
            list[AdverseEffect],
        ] = {}

        for effect in self.adverse_effects:
            result.setdefault(
                effect.symptom_id,
                [],
            ).append(effect)

        return result


