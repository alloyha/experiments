@dataclass(frozen=True)
class FeasibilityPolicy:
    max_regimen_size: int
    max_pairwise_interaction_severity: float


@dataclass(frozen=True)
class AdverseRiskState:
    symptom_id: int
    symptom_name: str

    aggregated_probability: float
    max_admissible_risk: float

    source_presentations: tuple[int, ...]

    @property
    def admissible(self) -> bool:
        return (
            self.aggregated_probability
            <= self.max_admissible_risk
            + EPSILON
        )


@dataclass(frozen=True)
class FeasibilityResult:
    feasible: bool
    violations: tuple[str, ...]

    adverse_risks: tuple[
        AdverseRiskState,
        ...
    ]


