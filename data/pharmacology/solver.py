"""
Exact regimen solver with:

- explicit symptom-set partitions;
- pathology-specific control/tolerance thresholds;
- regimen-level adverse-risk aggregation;
- explicit feasible set F_p;
- local treatment equilibrium.

The database is the source of policy.

For pathology p and symptom s:

    tau_{p,s}
        <- patologia_sintoma.limiar_tolerancia

    eta_{p,s}
        <- patologia_sintoma.limiar_controle

For adverse event generated by presentation m:

    kappa_{m,s}
        <- apresentacao_evento_adverso.risco_maximo_admissivel


Quantitative symptom state
==========================

    d_p(s)
        pathology burden

    a_M(s)
        adverse BURDEN:

        1 - Π_m(1 - burden_m(s))

    P_M(s)
        adverse OCCURRENCE probability:

        1 - Π_m(1 - probability_m(s))

    b_p,M(s)
        = d_p(s) + a_M(s)

    q_M(s)
        = Π_m(1 - e_m(s))

    r_p,M(s)
        = b_p,M(s) q_M(s)

    rho_p,M(s)
        = 1 - r/b


Set partitions
==============

    D_p
        pathology symptoms

    A_M
        adverse symptoms

    G_p(M)
        = D_p ∪ A_M

    O_p(M)
        = D_p ∩ A_M

    N_p(M)
        = A_M \\ D_p


Outcome partition:

    G_p(M)
        = C_p(M) ⊔ L_p(M) ⊔ U_p(M)

Controlled:

    rho_s >= eta_{p,s}

Tolerated:

    not controlled
    AND r_s <= tau_{p,s}

Unresolved:

    everything else


Important policy for symptoms that are NOT part of pathology
============================================================

A novel ADR has no tau_{p,s} or eta_{p,s} row in
patologia_sintoma.

Therefore it is NOT automatically treated as tolerated merely
because its burden is small.

For novel ADRs:

    control threshold:
        default eta = 1.0

    tolerance threshold:
        derived from the adverse relationship when possible.

The ADR feasibility constraint is independent from C/L/U.


Feasibility
===========

A regimen M is feasible iff:

    |M| <= max_regimen_size

and every pairwise interaction is below the configured maximum,

and for every generated adverse symptom s:

    P_M(s) <= kappa_M(s)

where:

    kappa_M(s)
        = minimum admissible threshold among selected
          presentations that can generate s.

Thus two individually acceptable risks may become collectively
infeasible after aggregation.


IMPORTANT
=========

Seed values are illustrative only.
This is a mathematical/optimization experiment, not medical software.
"""

