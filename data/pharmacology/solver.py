def regimen_label(
    model: ClinicalModel,
    regimen: tuple[int, ...],
) -> str:
    if not regimen:
        return "∅"

    return " + ".join(
        model.presentation_by_id[
            presentation_id
        ].label
        for presentation_id
        in regimen
    )


def format_set(
    model: ClinicalModel,
    symptom_ids: frozenset[int],
) -> str:
    if not symptom_ids:
        return "∅"

    return (
        "{ "
        + ", ".join(
            model.symptom_names[
                symptom_id
            ]
            for symptom_id
            in sorted(symptom_ids)
        )
        + " }"
    )


