class RegimenSolver:
    def __init__(
        self,
        model: ClinicalModel,
        *,
        lambda_complexity: float = 1.0,
        lambda_interaction: float = 1.0,

        max_regimen_size: int = (
            DEFAULT_MAX_REGIMEN_SIZE
        ),

        max_interaction_severity: float = (
            DEFAULT_MAX_INTERACTION_SEVERITY
        ),
    ) -> None:
        self.model = model

        self.lambda_complexity = (
            lambda_complexity
        )

        self.lambda_interaction = (
            lambda_interaction
        )

        self.feasibility_policy = (
            FeasibilityPolicy(
                max_regimen_size=(
                    max_regimen_size
                ),
                max_pairwise_interaction_severity=(
                    max_interaction_severity
                ),
            )
        )

        self.presentation_universe = frozenset(
            p.id
            for p in model.presentations
        )

    # ========================================================
    # POLICY LOOKUP
    # ========================================================

    def _thresholds_for_symptom(
        self,
        symptom_id: int,
    ) -> tuple[float, float]:
        """
        Returns:

            tau_{p,s}
            eta_{p,s}

        If s is not a pathology symptom, then no contextual
        pathology policy exists.

        Such symptoms are novel ADRs and therefore use explicit
        conservative fallback thresholds.
        """

        pathology_symptom = (
            self.model.pathology_by_symptom.get(
                symptom_id
            )
        )

        if pathology_symptom is None:
            return (
                DEFAULT_NOVEL_ADR_TOLERANCE,
                DEFAULT_NOVEL_ADR_CONTROL,
            )

        return (
            pathology_symptom.tolerance_threshold,
            pathology_symptom.control_threshold,
        )

    # ========================================================
    # SYMPTOM SPACE
    # ========================================================

    def symptom_space(
        self,
        regimen: Iterable[int],
    ) -> SymptomSpace:
        regimen_set = frozenset(
            regimen
        )

        unknown = (
            regimen_set
            - self.presentation_universe
        )

        if unknown:
            raise ValueError(
                "Unknown presentation IDs: "
                f"{sorted(unknown)}"
            )

        states = tuple(
            self._symptom_state(
                symptom_id,
                regimen_set,
            )
            for symptom_id in sorted(
                self.model.symptom_universe
            )
        )

        space = SymptomSpace(
            states=states,
        )

        space.validate_invariants()

        return space

    def _symptom_state(
        self,
        symptom_id: int,
        regimen: frozenset[int],
    ) -> SymptomState:
        d_s = self._pathology_burden(
            symptom_id
        )

        a_s = self._adverse_burden(
            symptom_id,
            regimen,
        )

        p_s = self._adverse_probability(
            symptom_id,
            regimen,
        )

        b_s = d_s + a_s

        q_s = self._attenuation_factor(
            symptom_id,
            regimen,
        )

        r_s = b_s * q_s

        tau_s, eta_s = (
            self._thresholds_for_symptom(
                symptom_id
            )
        )

        return SymptomState(
            symptom_id=symptom_id,
            symptom_name=(
                self.model.symptom_names[
                    symptom_id
                ]
            ),

            pathology_burden=d_s,
            adverse_burden=a_s,
            adverse_probability=p_s,

            generated_burden=b_s,
            attenuation_factor=q_s,
            residual_burden=r_s,

            tolerance_threshold=tau_s,
            control_threshold=eta_s,
        )

    # --------------------------------------------------------
    # d_p(s)
    # --------------------------------------------------------

    def _pathology_burden(
        self,
        symptom_id: int,
    ) -> float:
        symptom = (
            self.model.pathology_by_symptom.get(
                symptom_id
            )
        )

        if symptom is None:
            return 0.0

        return symptom.burden

    # --------------------------------------------------------
    # a_M(s) — burden
    # --------------------------------------------------------

    def _adverse_burden(
        self,
        symptom_id: int,
        regimen: frozenset[int],
    ) -> float:
        effects = (
            self.model.adverse_by_symptom.get(
                symptom_id,
                [],
            )
        )

        complement = 1.0
        found = False

        for effect in effects:
            if (
                effect.presentation_id
                not in regimen
            ):
                continue

            found = True

            complement *= (
                1.0
                - effect.expected_burden
            )

        if not found:
            return 0.0

        return 1.0 - complement

    # --------------------------------------------------------
    # P_M(s) — occurrence probability
    # --------------------------------------------------------

    def _adverse_probability(
        self,
        symptom_id: int,
        regimen: frozenset[int],
    ) -> float:
        effects = (
            self.model.adverse_by_symptom.get(
                symptom_id,
                [],
            )
        )

        complement = 1.0
        found = False

        for effect in effects:
            if (
                effect.presentation_id
                not in regimen
            ):
                continue

            found = True

            complement *= (
                1.0
                - effect.probability
            )

        if not found:
            return 0.0

        return 1.0 - complement

    # --------------------------------------------------------
    # q_M(s)
    # --------------------------------------------------------

    def _attenuation_factor(
        self,
        symptom_id: int,
        regimen: frozenset[int],
    ) -> float:
        factor = 1.0

        for effect in (
            self.model
            .therapeutic_by_symptom
            .get(
                symptom_id,
                [],
            )
        ):
            if (
                effect.presentation_id
                not in regimen
            ):
                continue

            factor *= (
                1.0
                - effect.expected_effect
            )

        return factor

    # ========================================================
    # REGIMEN-LEVEL ADR RISK
    # ========================================================

    def adverse_risk_states(
        self,
        regimen: Iterable[int],
    ) -> tuple[AdverseRiskState, ...]:
        regimen_set = frozenset(
            regimen
        )

        states: list[
            AdverseRiskState
        ] = []

        for symptom_id in sorted(
            self.model.adverse_by_symptom
        ):
            selected = [
                effect
                for effect
                in self.model.adverse_by_symptom[
                    symptom_id
                ]
                if (
                    effect.presentation_id
                    in regimen_set
                )
            ]

            if not selected:
                continue

            probability_complement = 1.0

            for effect in selected:
                probability_complement *= (
                    1.0
                    - effect.probability
                )

            aggregated_probability = (
                1.0
                - probability_complement
            )

            # Conservative aggregation of policy:
            #
            # if multiple selected presentations can cause
            # the same symptom, the strictest admissible
            # threshold dominates.
            max_admissible_risk = min(
                effect.max_admissible_risk
                for effect in selected
            )

            states.append(
                AdverseRiskState(
                    symptom_id=symptom_id,

                    symptom_name=(
                        self.model.symptom_names[
                            symptom_id
                        ]
                    ),

                    aggregated_probability=(
                        aggregated_probability
                    ),

                    max_admissible_risk=(
                        max_admissible_risk
                    ),

                    source_presentations=tuple(
                        sorted(
                            effect.presentation_id
                            for effect in selected
                        )
                    ),
                )
            )

        return tuple(states)

    # ========================================================
    # FEASIBILITY
    # ========================================================

    def check_feasibility(
        self,
        regimen: Iterable[int],
    ) -> FeasibilityResult:
        regimen_tuple = tuple(
            sorted(set(regimen))
        )

        violations: list[str] = []

        policy = (
            self.feasibility_policy
        )

        # ----------------------------------------------------
        # Cardinality
        # ----------------------------------------------------

        if (
            len(regimen_tuple)
            > policy.max_regimen_size
        ):
            violations.append(
                "regimen size "
                f"{len(regimen_tuple)} "
                "exceeds maximum "
                f"{policy.max_regimen_size}"
            )

        # ----------------------------------------------------
        # Pairwise interaction
        # ----------------------------------------------------

        for a, b in itertools.combinations(
            regimen_tuple,
            2,
        ):
            pair = (
                min(a, b),
                max(a, b),
            )

            severity = (
                self.model
                .interaction_by_pair
                .get(
                    pair,
                    0.0,
                )
            )

            if (
                severity
                >
                policy
                .max_pairwise_interaction_severity
                + EPSILON
            ):
                violations.append(
                    f"interaction {a}<->{b}: "
                    f"{severity:.4f} exceeds "
                    f"{policy.max_pairwise_interaction_severity:.4f}"
                )

        # ----------------------------------------------------
        # Aggregated ADR probability
        # ----------------------------------------------------

        adverse_risks = (
            self.adverse_risk_states(
                regimen_tuple
            )
        )

        for risk in adverse_risks:
            if risk.admissible:
                continue

            sources = ", ".join(
                str(x)
                for x
                in risk.source_presentations
            )

            violations.append(
                f"adverse risk "
                f"'{risk.symptom_name}': "
                f"P_M={risk.aggregated_probability:.4f} "
                f"> kappa={risk.max_admissible_risk:.4f}; "
                f"sources=[{sources}]"
            )

        return FeasibilityResult(
            feasible=not violations,
            violations=tuple(
                violations
            ),
            adverse_risks=adverse_risks,
        )

    # ========================================================
    # OBJECTIVE
    # ========================================================

    def evaluate(
        self,
        regimen: Iterable[int],
    ) -> Evaluation:
        regimen_tuple = tuple(
            sorted(set(regimen))
        )

        space = self.symptom_space(
            regimen_tuple
        )

        complexity_penalty = (
            self.lambda_complexity
            * sum(
                self.model
                .presentation_by_id[
                    presentation_id
                ]
                .complexity_cost

                for presentation_id
                in regimen_tuple
            )
        )

        interaction_penalty = (
            self.lambda_interaction
            * self._interaction_burden(
                regimen_tuple
            )
        )

        objective = (
            space.total_residual_burden
            + complexity_penalty
            + interaction_penalty
        )

        feasibility = (
            self.check_feasibility(
                regimen_tuple
            )
        )

        return Evaluation(
            regimen=regimen_tuple,

            symptom_space=space,

            complexity_penalty=(
                complexity_penalty
            ),

            interaction_penalty=(
                interaction_penalty
            ),

            objective=objective,

            feasibility=feasibility,
        )

    def _interaction_burden(
        self,
        regimen: tuple[int, ...],
    ) -> float:
        total = 0.0

        for a, b in itertools.combinations(
            regimen,
            2,
        ):
            pair = (
                min(a, b),
                max(a, b),
            )

            total += (
                self.model
                .interaction_by_pair
                .get(
                    pair,
                    0.0,
                )
            )

        return total

    # ========================================================
    # NEIGHBORHOOD
    # ========================================================

    def neighborhood(
        self,
        regimen: Iterable[int],
    ) -> frozenset[tuple[int, ...]]:
        current = frozenset(
            regimen
        )

        absent = (
            self.presentation_universe
            - current
        )

        result: set[
            tuple[int, ...]
        ] = set()

        # ADD
        for add_id in absent:
            result.add(
                tuple(
                    sorted(
                        current
                        | {add_id}
                    )
                )
            )

        # REMOVE
        for remove_id in current:
            result.add(
                tuple(
                    sorted(
                        current
                        - {remove_id}
                    )
                )
            )

        # SWITCH
        for remove_id in current:
            for add_id in absent:
                result.add(
                    tuple(
                        sorted(
                            (
                                current
                                - {remove_id}
                            )
                            | {add_id}
                        )
                    )
                )

        result.discard(
            tuple(sorted(current))
        )

        return frozenset(
            result
        )

    # ========================================================
    # LOCAL EQUILIBRIUM
    # ========================================================

    def is_local_equilibrium(
        self,
        regimen: Iterable[int],
    ) -> bool:
        current = self.evaluate(
            regimen
        )

        if not current.feasibility.feasible:
            return False

        for neighbor in self.neighborhood(
            current.regimen
        ):
            candidate = self.evaluate(
                neighbor
            )

            if (
                not candidate
                .feasibility
                .feasible
            ):
                continue

            if (
                candidate.objective
                <
                current.objective
                - EPSILON
            ):
                return False

        return True

    # ========================================================
    # EXHAUSTIVE SEARCH
    # ========================================================

    def enumerate_regimens(
        self,
    ) -> list[Evaluation]:
        presentation_ids = tuple(
            sorted(
                self.presentation_universe
            )
        )

        evaluations: list[
            Evaluation
        ] = []

        for size in range(
            len(presentation_ids) + 1
        ):
            for regimen in itertools.combinations(
                presentation_ids,
                size,
            ):
                evaluation = self.evaluate(
                    regimen
                )

                evaluation.is_local_equilibrium = (
                    self.is_local_equilibrium(
                        regimen
                    )
                )

                evaluations.append(
                    evaluation
                )

        evaluations.sort(
            key=lambda e: (
                not e.feasibility.feasible,
                e.objective,
                len(e.regimen),
                e.regimen,
            )
        )

        return evaluations


