@dataclass(frozen=True)
class Presentation:
    id: int
    drug_name: str
    description: str
    complexity_cost: float

    @property
    def label(self) -> str:
        return f"{self.drug_name} ({self.description})"


@dataclass(frozen=True)
class PathologySymptom:
    symptom_id: int
    symptom_name: str

    prevalence: float
    clinical_weight: float

    tolerance_threshold: float
    control_threshold: float

    @property
    def burden(self) -> float:
        return (
            self.prevalence
            * self.clinical_weight
        )


@dataclass(frozen=True)
class TherapeuticEffect:
    presentation_id: int
    symptom_id: int

    efficacy: float
    response_probability: float

    @property
    def expected_effect(self) -> float:
        return (
            self.efficacy
            * self.response_probability
        )


@dataclass(frozen=True)
class AdverseEffect:
    presentation_id: int
    symptom_id: int
    symptom_name: str

    probability: float

    severity: str
    severity_weight: float
    clinical_weight: float

    max_admissible_risk: float

    @property
    def expected_burden(self) -> float:
        """
        burden_m(s)

        Distinct from occurrence probability.
        """

        return (
            self.probability
            * self.severity_weight
            * self.clinical_weight
        )


@dataclass(frozen=True)
class Interaction:
    presentation_a_id: int
    presentation_b_id: int
    severity: float


# ============================================================
# PER-SYMPTOM STATE
# ============================================================


@dataclass(frozen=True)
class SymptomState:
    symptom_id: int
    symptom_name: str

    # d_p(s)
    pathology_burden: float

    # a_M(s)
    adverse_burden: float

    # P_M(s)
    adverse_probability: float

    # b_p,M(s)
    generated_burden: float

    # q_M(s)
    attenuation_factor: float

    # r_p,M(s)
    residual_burden: float

    # tau
    tolerance_threshold: float

    # eta
    control_threshold: float

    @property
    def relative_reduction(self) -> float:
        if self.generated_burden <= EPSILON:
            return 0.0

        return (
            1.0
            - (
                self.residual_burden
                / self.generated_burden
            )
        )

    @property
    def generated(self) -> bool:
        return (
            self.generated_burden
            > EPSILON
        )

    @property
    def pathology_generated(self) -> bool:
        return (
            self.pathology_burden
            > EPSILON
        )

    @property
    def adverse_generated(self) -> bool:
        return (
            self.adverse_burden
            > EPSILON
        )

    @property
    def controlled(self) -> bool:
        if not self.generated:
            return False

        return (
            self.relative_reduction
            >= self.control_threshold
            - EPSILON
        )

    @property
    def tolerated(self) -> bool:
        if not self.generated:
            return False

        if self.controlled:
            return False

        return (
            self.residual_burden
            <= self.tolerance_threshold
            + EPSILON
        )

    @property
    def unresolved(self) -> bool:
        if not self.generated:
            return False

        return not (
            self.controlled
            or self.tolerated
        )


# ============================================================
# SYMPTOM SPACE
# ============================================================


@dataclass(frozen=True)
class SymptomSpace:
    states: tuple[SymptomState, ...]

    @property
    def disease_support(self) -> frozenset[int]:
        return frozenset(
            s.symptom_id
            for s in self.states
            if s.pathology_generated
        )

    @property
    def adverse_support(self) -> frozenset[int]:
        return frozenset(
            s.symptom_id
            for s in self.states
            if s.adverse_generated
        )

    @property
    def generated_support(self) -> frozenset[int]:
        return frozenset(
            s.symptom_id
            for s in self.states
            if s.generated
        )

    @property
    def overlap_adverse_support(
        self,
    ) -> frozenset[int]:
        return (
            self.disease_support
            & self.adverse_support
        )

    @property
    def novel_adverse_support(
        self,
    ) -> frozenset[int]:
        return (
            self.adverse_support
            - self.disease_support
        )

    @property
    def controlled_support(
        self,
    ) -> frozenset[int]:
        return frozenset(
            s.symptom_id
            for s in self.states
            if s.controlled
        )

    @property
    def tolerated_support(
        self,
    ) -> frozenset[int]:
        return frozenset(
            s.symptom_id
            for s in self.states
            if s.tolerated
        )

    @property
    def unresolved_support(
        self,
    ) -> frozenset[int]:
        return frozenset(
            s.symptom_id
            for s in self.states
            if s.unresolved
        )

    @property
    def total_residual_burden(
        self,
    ) -> float:
        return sum(
            s.residual_burden
            for s in self.states
        )

    def validate_invariants(self) -> None:
        D = self.disease_support
        A = self.adverse_support
        G = self.generated_support

        O = self.overlap_adverse_support
        N = self.novel_adverse_support

        C = self.controlled_support
        L = self.tolerated_support
        U = self.unresolved_support

        assert G == D | A

        assert O == D & A
        assert N == A - D

        assert O.isdisjoint(N)
        assert O | N == A

        assert C.isdisjoint(L)
        assert C.isdisjoint(U)
        assert L.isdisjoint(U)

        assert (
            C | L | U
        ) == G


