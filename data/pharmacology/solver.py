def resolve_pathology(
    con: duckdb.DuckDBPyConnection,
    value: str,
) -> int:
    try:
        pathology_id = int(value)

        row = con.execute(
            """
            SELECT id
            FROM patologia
            WHERE id = ?
            """,
            [pathology_id],
        ).fetchone()

        if row is not None:
            return pathology_id

    except ValueError:
        pass

    row = con.execute(
        """
        SELECT id
        FROM patologia
        WHERE lower(nome) = lower(?)
        """,
        [value],
    ).fetchone()

    if row is None:
        available = con.execute(
            """
            SELECT id, nome
            FROM patologia
            ORDER BY id
            """
        ).fetchall()

        options = ", ".join(
            f"{pathology_id}:{name}"
            for pathology_id, name
            in available
        )

        raise ValueError(
            f"Patologia '{value}' não encontrada. "
            f"Disponíveis: {options}"
        )

    return row[0]


